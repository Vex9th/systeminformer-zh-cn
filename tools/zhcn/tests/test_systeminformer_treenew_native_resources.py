    def test_retired_runtime_keys_have_no_exact_non_native_consumer(self) -> None:
        reviewed_keys = {"Committed", "Home directory", "References"}
        consumers = {key: [] for key in reviewed_keys}

        for root in (APP_ROOT, REPO_ROOT / "phlib", REPO_ROOT / "plugins", REPO_ROOT / "tools"):
            for path in root.rglob("*"):
                if path.suffix.lower() not in {".c", ".cpp", ".h", ".rc"}:
                    continue
                if "tests" in path.parts or path.name == "phtranslation_zhcn.c":
                    continue
                source = path.read_text(encoding="utf-8-sig", errors="ignore")
                if path.suffix.lower() in {".c", ".cpp", ".h"}:
                    source = self.audit.mask_c_comments(source)
                for key in reviewed_keys:
                    if path == APP_ROOT / "SystemInformer.rc":
                        continue
                    if re.search(rf'(?<![A-Za-z])(?:L)?"{re.escape(key)}"', source):
                        consumers[key].append(path.relative_to(REPO_ROOT).as_posix())

        self.assertEqual(
            {"Committed": [], "Home directory": [], "References": []},
            consumers,
        )
        self.assertTrue(reviewed_keys.isdisjoint(RUNTIME_COMPATIBILITY_KEYS))

    def test_systeminformer_has_no_direct_static_treenew_findings(self) -> None:
        unresolved = []
        for path in APP_ROOT.glob("*.c"):
            entries = []
            self.audit.scan_c_file(str(path), entries)
            unresolved.extend(entry for entry in entries if entry["category"] in {"c_treenew_col", "c_treenew_empty"})
        self.assertEqual([], unresolved)


