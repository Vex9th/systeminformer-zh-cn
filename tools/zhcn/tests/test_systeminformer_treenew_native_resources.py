def load_audit_module():
    path = REPO_ROOT / "tools" / "zhcn" / "audit.py"
    spec = importlib.util.spec_from_file_location("treenew_native_audit", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def parse_stringtable(path: pathlib.Path) -> dict[str, str]:
    return {
        symbol: value.replace('""', '"')
        for symbol, value in re.findall(
            r'(?m)^\s*(IDS_PH_[A-Z0-9_]+)\s+"((?:[^"]|"")*)"\s*$',
            path.read_text(encoding="utf-8-sig"),
        )
    }


class SystemInformerTreeNewNativeResourceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.audit = load_audit_module()

    def collect_routes(self, sources: Optional[dict[str, str]] = None) -> Counter:
        sources = sources or {}
        actual = Counter()
        for file_name in sorted({row[0] for row in EXPECTED_ROUTES}):
            source = sources.get(file_name)
            if source is None:
                source = (APP_ROOT / file_name).read_text(encoding="utf-8-sig")
            source = self.audit.mask_c_comments(source)
            for name, args, _spans, _start in self.audit.find_calls(source, APIS):
                if len(args) < 4:
                    continue
                match = re.fullmatch(r"PhGetApplicationUiString\(\s*(IDS_PH_[A-Z0-9_]+)\s*\)", args[3].strip())
                if match and match.group(1) in set(RESOURCE_BY_ENGLISH.values()):
                    actual[(file_name, name, args[1].strip(), match.group(1))] += 1
        return actual

    def test_all_274_calls_keep_exact_file_api_column_and_resource_routes(self) -> None:
        self.assertEqual(EXPECTED_ROUTES, self.collect_routes())
        self.assertEqual(274, sum(EXPECTED_ROUTES.values()))
        self.assertEqual(18, len({row[0] for row in EXPECTED_ROUTES}))

    def test_route_contract_rejects_resource_swap(self) -> None:
        source = (APP_ROOT / "findobj.c").read_text(encoding="utf-8-sig")
        mutated = source.replace(
            "PhGetApplicationUiString(IDS_PH_LISTVIEW_PROCESS)",
            "PhGetApplicationUiString(IDS_PH_TOKEN_TYPE)",
            1,
        )
        self.assertNotEqual(source, mutated)
        with self.assertRaises(AssertionError):
            self.assertEqual(EXPECTED_ROUTES, self.collect_routes({"findobj.c": mutated}))

    def test_170_resources_are_contiguous_bilingual_and_owned_by_one_layer(self) -> None:
        header = (APP_ROOT / "resource.h").read_text(encoding="utf-8-sig")
        english = parse_stringtable(APP_ROOT / "SystemInformer.rc")
        chinese = parse_stringtable(APP_ROOT / "SystemInformer.zh-cn.rc")
        data = json.loads((REPO_ROOT / "tools" / "zhcn" / "zh-CN.json").read_text(encoding="utf-8"))

        for symbol, resource_id, en, zh in NEW_RESOURCES:
            with self.subTest(symbol=symbol):
                self.assertRegex(header, rf"(?m)^#define\s+{symbol}\s+{resource_id}$")
                self.assertEqual(en, english.get(symbol))
                self.assertEqual(zh, chinese.get(symbol))

        translations = {en: zh for _symbol, _resource_id, en, zh in NEW_RESOURCES}
        translations.update({en: zh for en, (_symbol, zh) in REUSED_RESOURCES.items()})
        for en, zh in translations.items():
            layer = "strings" if en in RUNTIME_COMPATIBILITY_KEYS else "native_strings"
            other = "native_strings" if layer == "strings" else "strings"
            self.assertEqual(zh, data[layer].get(en), en)
            self.assertNotIn(en, data[other], en)

        self.assertRegex(header, r"(?m)^#define IDS_PH_LAST\s+IDS_PH_MENU_COLLAPSE_ALL_PLAIN$")
        self.assertRegex(header, r"(?m)^#define _APS_NEXT_SYMED_VALUE\s+3370$")
        self.assertEqual(1370, len(english))
        self.assertEqual(1370, len(chinese))

